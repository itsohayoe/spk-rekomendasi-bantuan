-- ============================================================
-- SCHEMA DATABASE
-- Sistem Pendukung Keputusan Rekomendasi Bantuan
-- ============================================================

CREATE SCHEMA IF NOT EXISTS dtsen;


-- ============================================================
-- 1. VIEW INPUT DATA KELUARGA
-- Sumber: dtsen.dataset_keluarga
-- Digunakan sebagai input pipeline preprocessing.
-- ============================================================

CREATE OR REPLACE VIEW dtsen.vw_input_keluarga AS
SELECT
    id_keluarga,
    kode_provinsi,
    kode_kabupaten_kota,
    kode_kecamatan,
    kode_kelurahan_desa,
    desil_nasional_v3 AS desil_nasional,
    jumlah_anggota_keluarga,
    luas_lantai,
    status_kepemilikan_rumah,
    jenis_atap_terluas,
    jenis_dinding_terluas,
    jenis_lantai_terluas,
    sumber_air_minum_utama,
    sumber_penerangan_utama,
    fasilitas_bab,
    jenis_kloset,
    pembuangan_akhir_tinja,
    bahan_bakar_utama_memasak,
    aset_bergerak_lemari_es,
    aset_bergerak_sepeda_motor,
    aset_bergerak_kapal_perahu_motor,
    aset_bergerak_smartphone
FROM dtsen.dataset_keluarga;


-- ============================================================
-- 2. VIEW INPUT DATA ANGGOTA KELUARGA
-- Sumber: dtsen.dataset_anggota_keluarga
-- Digunakan sebagai input pipeline preprocessing.
-- ============================================================

CREATE OR REPLACE VIEW dtsen.vw_input_anggota_keluarga AS
SELECT
    id_keluarga,
    umur,
    jenis_kelamin,
    partisipasi_sekolah,
    ijazah_tertinggi_yang_dimiliki,
    status_dalam_pekerjaan_utama,
    kondisi_gizi,
    penyakit_kronis,
    penglihatan,
    pendengaran,
    berjalan_atau_naik_tangga,
    menggunakan_tangan_jari,
    belajar_kemampuan_intelektual,
    pengendalian_perilaku,
    berbicara_komunikasi,
    mengurus_diri,
    mengingat_berkonsentrasi
FROM dtsen.dataset_anggota_keluarga;


-- ============================================================
-- 3. TABEL HASIL FEATURE ENGINEERING
-- Satu record untuk setiap keluarga.
-- ============================================================

CREATE TABLE IF NOT EXISTS dtsen.dataset_feature (
    id_keluarga              VARCHAR(50) PRIMARY KEY,
    kode_provinsi             VARCHAR(2),
    kode_kabupaten_kota       VARCHAR(4),
    kode_kecamatan            VARCHAR(7),
    kode_kelurahan_desa       VARCHAR(10),
    desil_nasional            SMALLINT,

    ada_asn                   SMALLINT,
    ada_anak_sekolah          SMALLINT,
    ada_balita                SMALLINT,
    ada_lansia                SMALLINT,
    belum_sekolah             SMALLINT,
    putus_sekolah             SMALLINT,
    ijazah_rendah             SMALLINT,

    penyakit_kronis           SMALLINT,
    balita_gizi_buruk         SMALLINT,
    gangguan_fungsional       SMALLINT,

    hunian_padat              SMALLINT,
    atap_tidak_layak          SMALLINT,
    dinding_tidak_layak       SMALLINT,
    lantai_tidak_layak        SMALLINT,
    air_tidak_layak           SMALLINT,
    sanitasi_tidak_layak      SMALLINT,

    penerangan_tidak_layak    SMALLINT,
    bahan_bakar_tidak_layak   SMALLINT,

    rumah_bukan_milik_sendiri SMALLINT,
    tidak_punya_kulkas        SMALLINT,
    tidak_punya_motor         SMALLINT,
    tidak_punya_smartphone    SMALLINT,

    CONSTRAINT fk_feature_keluarga
        FOREIGN KEY (id_keluarga)
        REFERENCES dtsen.dataset_keluarga (id_keluarga)
);


-- ============================================================
-- 4. TABEL PROFIL DEPRIVASI
-- Satu keluarga dapat memiliki banyak indikator.
-- ============================================================

CREATE TABLE IF NOT EXISTS dtsen.data_deprivasi (
    id_keluarga              VARCHAR(50) NOT NULL,
    indikator                VARCHAR(100) NOT NULL,
    kode_provinsi            VARCHAR(2),
    kode_kabupaten_kota      VARCHAR(4),
    kode_kecamatan           VARCHAR(7),
    kode_kelurahan_desa      VARCHAR(10),
    desil_nasional           SMALLINT,
    status                   SMALLINT,
    nilai                    DOUBLE PRECISION,
    is_complete              SMALLINT,

    CONSTRAINT data_deprivasi_pkey
        PRIMARY KEY (id_keluarga, indikator),

    CONSTRAINT fk_deprivasi_feature
        FOREIGN KEY (id_keluarga)
        REFERENCES dtsen.dataset_feature (id_keluarga)
);


-- ============================================================
-- 5. TABEL HASIL REKOMENDASI
-- Satu keluarga dapat memiliki banyak rekomendasi program.
-- ============================================================

CREATE TABLE IF NOT EXISTS dtsen.data_rekomendasi (
    id_rekomendasi           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_keluarga              VARCHAR(50) NOT NULL,
    kode_provinsi            VARCHAR(2),
    kode_kabupaten_kota      VARCHAR(4),
    kode_kecamatan           VARCHAR(7),
    kode_kelurahan_desa      VARCHAR(10),
    desil_nasional           SMALLINT,
    program                  VARCHAR(100),
    status                   SMALLINT,
    skor                     DOUBLE PRECISION,
    prioritas                SMALLINT,
    asesmen                  SMALLINT,
    is_complete              SMALLINT,
    indikator_deprivasi      TEXT,

    CONSTRAINT fk_rekomendasi_feature
        FOREIGN KEY (id_keluarga)
        REFERENCES dtsen.dataset_feature (id_keluarga)
);


-- ============================================================
-- 6. TABEL REFERENSI WILAYAH
-- Digunakan untuk menerjemahkan kode wilayah menjadi nama wilayah.
-- ============================================================

CREATE TABLE IF NOT EXISTS dtsen.ref_wilayah (
    kode_provinsi             VARCHAR(2),
    kode_kabupaten_kota       VARCHAR(4),
    kode_kecamatan            VARCHAR(7),
    kode_kelurahan_desa       VARCHAR(10) PRIMARY KEY,
    nama_provinsi             TEXT,
    nama_kabupaten_kota       TEXT,
    nama_kecamatan            TEXT,
    nama_kelurahan_desa       TEXT
);